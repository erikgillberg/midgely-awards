#!/usr/bin/env python3
"""Turn docs/story-sources/<slug>.md tables into public/case-sources.js, the references on each teardown page.
Run after editing a sources file: python3 tools/build-sources.py"""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for path in sorted(glob.glob(os.path.join(ROOT, "docs/story-sources/*.md"))):
    slug = os.path.basename(path)[:-3]
    seen, rows = set(), []
    last_url = ""
    for line in open(path):
        if not line.startswith("|") or line.startswith("|---") or "Claim" in line.split("|")[1]:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            continue
        source, url = cells[1], cells[2]
        if url.lower() in ("same", "same as above", '"'):
            url = last_url
        m = re.search(r"https?://\S+", url)
        url = m.group(0).rstrip(".,;)") if m else ""
        last_url = url or last_url
        key = (source, url)
        if key in seen or not source:
            continue
        seen.add(key)
        rows.append({"source": source, "url": url})
    if rows:
        out[slug] = rows
js = "// Generated by tools/build-sources.py from docs/story-sources/*.md. Do not edit by hand.\nexport const CASE_SOURCES = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n"
open(os.path.join(ROOT, "public/case-sources.js"), "w").write(js)
print({k: len(v) for k, v in out.items()})
